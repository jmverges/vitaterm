#!/usr/bin/env python3
"""Copy the card's bitmap fonts into the server package, for `dsterm view`.

    python3 tools/genviewfont.py          # writes dsterm/dsfont.py

`dsterm view` draws the DS's two screens pixel for pixel, so it needs the very
glyphs the card draws with. Those live in dsclient/source/font*.h (generated
by tools/genfont.py from the BDFs), which an installed server does not have,
so this copies the tables into a Python module. tests/test_dsfont.py fails if
the copy and the headers ever disagree.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "dsclient" / "source"
OUT = REPO / "dsterm" / "dsfont.py"

# (header, table, extension table, cell width, cell height): the UI font every
# bottom screen and the 42x24 terminal use, then the two smaller terminals.
FONTS = (
    ("font.h", "font6x8", "font6x8_ext", 6, 8),
    ("font5x7.h", "font_term", "font_term_ext", 5, 7),
    ("font4x6.h", "font_term", "font_term_ext", 4, 6),
)


def table(text: str, name: str) -> list[list[int]]:
    m = re.search(r"static const uint8_t\s+%s\[\d+\]\[\d+\]\s*=\s*\{(.*?)\n\};" % name,
                  text, re.S)
    if not m:
        raise SystemExit(f"no table {name}")
    rows = re.findall(r"\{([^{}]*)\}", m.group(1))
    return [[int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]+", row)] for row in rows]


def read_fonts() -> dict[tuple[int, int], tuple[list[list[int]], list[list[int]]]]:
    fonts = {}
    for header, name, ext, w, h in FONTS:
        text = (SOURCE / header).read_text()
        fonts[(w, h)] = (table(text, name), table(text, ext))
    return fonts


def render(fonts) -> str:
    out = [
        '"""Generated by tools/genviewfont.py from dsclient/source/font*.h -- do not',
        "edit by hand.",
        "",
        "The card's own bitmap fonts, for `dsterm view` to draw the screens with.",
        "Derived from the Spleen font, Copyright (c) 2018-2026 Frederic Cambus,",
        "BSD 2-Clause (THIRD_PARTY_NOTICES.md).",
        "Each glyph is one int per row, the leftmost pixel the highest bit of the",
        "cell's width. ASCII 0x20-0x7E, then the extended table from 0x80",
        '(extmap.py says which codepoint each is)."""',
        "",
        "FIRST = 0x20",
        "EXT_BASE = 0x80",
        "",
        "# (cell width, cell height) -> (ASCII glyphs, extended glyphs)",
        "FONTS = {",
    ]
    for (w, h), (ascii_rows, ext_rows) in fonts.items():
        out.append(f"    ({w}, {h}): (")
        for rows in (ascii_rows, ext_rows):
            out.append("        (")
            for glyph in rows:
                out.append("            (" + ", ".join(f"0x{v:02X}" for v in glyph) + "),")
            out.append("        ),")
        out.append("    ),")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    OUT.write_text(render(read_fonts()))
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
